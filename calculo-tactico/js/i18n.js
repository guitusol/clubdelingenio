class I18nEngine {
  constructor() {
    this.currentLang = this.detectLanguage();
  }

  detectLanguage() {
    // 1. URL (?lang=...)
    try {
      const params = new URLSearchParams(window.location.search);
      const urlLang = params.get('lang');
      if (urlLang && CALC_I18N_LANGUAGES[urlLang.toLowerCase()]) {
        return urlLang.toLowerCase();
      }
    } catch (e) {}

    // 2. localStorage
    try {
      const saved = localStorage.getItem('calc_tactico_lang');
      if (saved && CALC_I18N_LANGUAGES[saved]) {
        return saved;
      }
    } catch (e) {}

    // 3. Navegador
    try {
      const navLang = (navigator.language || navigator.userLanguage || 'es').toLowerCase();
      if (navLang.startsWith('en')) return 'en';
      if (navLang.startsWith('fr')) return 'fr';
      if (navLang.startsWith('de')) return 'de';
      if (navLang.startsWith('ca') || navLang.includes('catalan')) return 'ca';
      if (navLang.startsWith('va') || navLang.includes('valencian')) return 'va';
      if (navLang.startsWith('eu') || navLang.includes('basque')) return 'eu';
      if (navLang.startsWith('gl') || navLang.includes('galician')) return 'gl';
      if (navLang.startsWith('ja') || navLang.includes('japanese')) return 'ja';
    } catch (e) {}

    return 'es';
  }

  setLanguage(langCode) {
    if (!CALC_I18N_LANGUAGES[langCode]) return;
    this.currentLang = langCode;
    try {
      localStorage.setItem('calc_tactico_lang', langCode);
    } catch (e) {}
    this.applyTranslations();

    // Actualizar indicador en cabecera
    const codeEl = document.getElementById('current-lang-code');
    if (codeEl) {
      codeEl.textContent = langCode.toUpperCase();
    }
  }

  t(key, params = {}) {
    const dict = CALC_I18N_LANGUAGES[this.currentLang] || CALC_I18N_LANGUAGES['es'];
    let text = dict[key] || CALC_I18N_LANGUAGES['es'][key] || key;

    // Sustituir variables {nombre}
    Object.keys(params).forEach(p => {
      text = text.replace(new RegExp(`\\{${p}\\}`, 'g'), params[p]);
    });

    return text;
  }

  applyTranslations() {
    // 1. Textos data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (key) {
        el.innerHTML = this.t(key);
      }
    });

    // 2. Títulos data-i18n-title
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
      const key = el.getAttribute('data-i18n-title');
      if (key) {
        el.setAttribute('title', this.t(key));
      }
    });

    // 3. Botón de idioma en header
    const codeEl = document.getElementById('current-lang-code');
    if (codeEl) {
      codeEl.textContent = this.currentLang.toUpperCase();
    }
  }

  getLanguagesList() {
    return Object.values(CALC_I18N_LANGUAGES);
  }
}

if (typeof window !== 'undefined') {
  window.i18n = new I18nEngine();
}
